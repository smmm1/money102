function advanceHouseholdAges(life:LifeRecord):LifeRecord["householdScene"] {
  const scene=life.householdScene
  if(!scene) return scene
  const familyEntry=life.timeline.find(entry=>entry.title==="ความสัมพันธ์และการสร้างครอบครัว"&&entry.detail.includes("สร้างครอบครัวและมีลูก"))
  const childAges=scene.childAges ?? Array.from({length:Math.max(0,scene.children)},()=>Math.max(0,life.age-(familyEntry?.age ?? life.age)))
  return {
    ...scene,
    ...(scene.partner ? {partnerAge:(scene.partnerAge ?? life.age)+1} : {}),
    childAges:childAges.map(age=>age+1)
  }
}

export function advanceLife(life:LifeRecord):LifeRecord {
  if(life.status!=="alive"||life.pendingEvent) return life
  const nextAge=life.age+1
  const year=life.bornYear+nextAge
  if(nextAge>=life.expectedLifespan) {
    return {...life,age:nextAge,status:"ended",endedAt:new Date().toISOString(),timeline:[{id:uid(),age:nextAge,year,title:"เรื่องราวชีวิตเดินทางมาถึงปลายทาง",detail:"ชีวิตหนึ่งได้สิ้นสุดลง เหลือไว้ซึ่งความทรงจำและผลของการตัดสินใจ"},...life.timeline]}
  }
  const nextLife={...life,age:nextAge,householdScene:advanceHouseholdAges(life)}
  const event=eventForYear(nextLife,year) ?? sceneMilestoneEvent(nextLife,year) ?? makePersonalEvent(nextLife,year)
  return {...nextLife,pendingEvent:event}
}

export function estimateChoiceChance(life:LifeRecord,selected:LifeChoice):number {
  let chance=selected.chance
  if(selected.requirement && life.stats.education<45) chance-=10
  chance+=Math.round((life.stats.skills-40)*0.12)
  chance+=Math.round((life.stats.education-40)*0.08)
  const resourceSensitive=["university","tutor","better-school","small-business","craft","move","borrow-more","refinance","support","checkup","room-share","near-work","short-course"]
  if(resourceSensitive.includes(selected.id)) {
    chance+=Math.max(-8,Math.min(8,Math.round((life.stats.wealth-12000)/6000)))
    if(life.householdDebt>30000) chance-=5
  }
  if(["family-help","grandparents","share-care","take-care","check-relatives","protect-family","stay-connected","shared-support","care-plan","family-schedule"].includes(selected.id)) {
    chance+=Math.round((life.stats.relationships-50)*0.12)
  }
  if(["exercise","sports","health","routine","evacuate","stay-safe","plan-appointments"].includes(selected.id)) {
    chance+=Math.round((life.stats.health-50)*0.1)
  }
  if(["move","better-school","university","tutor","near-work"].includes(selected.id) && life.areaType.includes("ชนบท")) chance-=4
  if(life.stats.stress>=70) chance-=4
  if(life.stats.health<25 && ["work","promotion","side-job","short-intern"].includes(selected.id)) chance-=5
  return Math.max(5,Math.min(95,chance))
}

export function resolveLifeChoice(life:LifeRecord,choiceId:string):LifeRecord {
  const event=life.pendingEvent
  if(!event) return life
  const selected=event.choices.find(item=>item.id===choiceId)
  if(!selected) return life
  const chance=estimateChoiceChance(life,selected)
  const success=Math.random()*100<chance
  const effects=success?selected.successEffects:selected.failureEffects
  const stats={...life.stats}
  for(const [key,value] of Object.entries(effects)) {
    const statKey=key as keyof LifeStats
    stats[statKey]=statKey==="wealth"?Math.max(-100000,stats.wealth+(value??0)):clamp(stats[statKey]+(value??0))
  }
  const result=success?selected.successOutcome:selected.failureOutcome
  let occupation=life.occupation
  if(success){
    const careerChoices:Record<string,string>={"university":"นักศึกษา","vocational":"นักเรียนสายอาชีพ","stable-job":"พนักงานประจำ","learn-job":"ลูกจ้างฝึกทักษะ/พนักงานใหม่","small-business":"เจ้าของกิจการขนาดเล็ก","work":"ลูกจ้าง/แรงงาน","craft":"อาชีพอิสระ/งานฝีมือ","promotion":"หัวหน้างาน/ผู้จัดการ","reskill":"กำลังพัฒนาทักษะอาชีพ"}
    occupation=careerChoices[choiceId]??occupation
  }
  let householdDebt=life.householdDebt
  if(choiceId==="borrow-more") householdDebt+=success?25000:40000
  if(choiceId==="refinance"&&success) householdDebt=Math.max(0,householdDebt-5000)
  const detail=`${selected.label} — ${result} (โอกาสสำเร็จโดยประมาณในเกม ${chance}%)`
  const entry:LifeEntry={id:uid(),age:life.age,year:event.year,title:event.title,detail,sourceTitle:event.sourceTitle,sourceUrl:event.sourceUrl,sourceNote:event.sourceNote}
  const householdScene:NonNullable<LifeRecord["householdScene"]> = {...(life.householdScene ?? {partner:false,children:0,pets:[],housekeeper:false,vehicle:null})}
  if(success){
    if(choiceId==="start-family"){
      householdScene.partner=true
      householdScene.partnerAge=life.age
      if(householdScene.children<1){
        householdScene.children=1
        householdScene.childAges=[...(householdScene.childAges ?? []),0]
      }
    }
    if(choiceId==="partner-first"){
      householdScene.partner=true
      householdScene.partnerAge=life.age
    }
    if(choiceId==="adopt-cat" && !householdScene.pets.includes("cat")) householdScene.pets=[...householdScene.pets,"cat"]
    if(choiceId==="adopt-dog" && !householdScene.pets.includes("dog")) householdScene.pets=[...householdScene.pets,"dog"]
    if(choiceId==="buy-motorcycle") householdScene.vehicle="motorcycle"
    if(choiceId==="buy-car") householdScene.vehicle="car"
    if(choiceId==="hire-housekeeper") householdScene.housekeeper=true
  }
  const sceneDecisions = event.sceneKey ? [...new Set([...(life.sceneDecisions ?? []),event.sceneKey])] : (life.sceneDecisions ?? [])
  return {...life,stats,occupation,householdDebt,householdScene,sceneDecisions,pendingEvent:null,timeline:[entry,...life.timeline]}
}

export function validateLifeRecord(value:unknown):value is LifeRecord {
  if(!value||typeof value!=="object") return false
  const life=value as Partial<LifeRecord>
  return typeof life.id==="string"&&typeof life.name==="string"&&life.country==="ประเทศไทย"&&
    typeof life.province==="string"&&typeof life.bornYear==="number"&&typeof life.age==="number"&&
    typeof life.expectedLifespan==="number"&&Array.isArray(life.timeline)&&
    !!life.stats&&typeof life.stats.health==="number"&&typeof life.stats.stress==="number"&&typeof life.stats.wealth==="number"&&Array.isArray(life.parents)&&typeof life.family==="string"&&typeof life.region==="string"
}
